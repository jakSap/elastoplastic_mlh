def setup(tag, Y0=None, name=None):
    r = T.rung("P1", tag)
    src = os.path.join(HERE, "..", "ics", "P1_{}.h5".format(tag))
    if not os.path.exists(src):
        raise SystemExit("missing {} -- run `mto.py plan <cand> -t P` once to create it".format(src))
    D = os.path.join(HERE, "runs", name or tag)
    os.makedirs(os.path.join(D, "output"), exist_ok=True)
    with h5py.File(src, "r") as f:
        x, v, m, u = f["x"][:], f["v"][:], f["m"][:], f["u"][:]
    N = len(m)
    pos = np.zeros((N, 3)); pos[:, :2] = x + OFFSET
    vel = np.zeros((N, 3)); vel[:, :2] = v
    with h5py.File(os.path.join(D, "ic.hdf5"), "w") as f:
        h = f.create_group("Header")
        npart = np.array([N, 0, 0, 0, 0, 0], dtype=np.int32)
        h.attrs["NumPart_ThisFile"] = npart
        h.attrs["NumPart_Total"] = npart.astype(np.uint32)
        h.attrs["NumPart_Total_HighWord"] = np.zeros(6, dtype=np.uint32)
        h.attrs["MassTable"] = np.zeros(6)
        for k, val in (("Time", 0.0), ("Redshift", 0.0), ("BoxSize", 2 * OFFSET),
                       ("NumFilesPerSnapshot", 1), ("Omega0", 0.0), ("OmegaLambda", 0.0),
                       ("HubbleParam", 1.0), ("Flag_Sfr", 0), ("Flag_Cooling", 0),
                       ("Flag_StellarAge", 0), ("Flag_Metals", 0), ("Flag_Feedback", 0),
                       ("Flag_DoublePrecision", 1)):
            h.attrs[k] = val
        g = f.create_group("PartType0")
        g.create_dataset("Coordinates", data=pos)
        g.create_dataset("Velocities", data=vel)
        g.create_dataset("Masses", data=m)
        g.create_dataset("InternalEnergy", data=u)
        g.create_dataset("ParticleIDs", data=np.arange(1, N + 1, dtype=np.uint32))
        g.create_dataset("CompositionType", data=np.zeros(N, dtype=np.int32))
    mat = r["materials"][0]
    open(os.path.join(D, "rod.params"), "w").write(PARAMS.format(
        tag=tag, dump=r["dump"], t_end=r["t_end"], box=2 * OFFSET, mu=mat["mu"], Y0=Y0 if Y0 is not None else mat["Y0"]))
    return D


def convert(D):
    out = os.path.join(D, "conv")
    os.makedirs(out, exist_ok=True)
    for old in glob.glob(os.path.join(out, "*.h5")):
        os.remove(old)
    for k, snap in enumerate(sorted(glob.glob(os.path.join(D, "output", "snapshot_*.hdf5")))):
        with h5py.File(snap, "r") as f:
            t = float(f["Header"].attrs["Time"])
            g = f["PartType0"]
            o = np.argsort(g["ParticleIDs"][:])
            x = g["Coordinates"][:][o, :2] - OFFSET
            v = g["Velocities"][:][o, :2]
            m, rho, u = g["Masses"][:][o], g["Density"][:][o], g["InternalEnergy"][:][o]
            S = g["StressTensor"][:][o] if "StressTensor" in g else None
        with h5py.File(os.path.join(out, "{:06d}.h5".format(k)), "w") as d:
            d["x"], d["v"], d["m"], d["rho"], d["u"] = x, v, m, rho, u
            if S is not None:
                S = S.reshape(len(m), -1)
                d["Sxx"], d["Sxy"], d["Syy"] = S[:, 0], S[:, 1], S[:, 4] if S.shape[1] == 9 else S[:, 3]
            d["time"] = np.array([t])
            d["energy"] = np.array([float(np.sum(m * (u + 0.5 * np.sum(v * v, axis=1))))])
    return out


def run(tag, Y0=None, name=None):
    D = setup(tag, Y0, name)
    with open(os.path.join(D, "run.log"), "w") as lf:
        rc = subprocess.run([GIZMO, "rod.params"], cwd=D, stdout=lf, stderr=subprocess.STDOUT).returncode
    out = convert(D)
    return name or tag, rc, len(glob.glob(os.path.join(out, "*.h5")))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("tags", nargs="+")
    ap.add_argument("-j", type=int, default=2)
    ap.add_argument("--convert-only", action="store_true")
    ap.add_argument("--Y0", type=float, nargs="+", help="scan: one run per value, runs/<tag>_Y<val>")
    a = ap.parse_args()
    if a.convert_only:
        for t in a.tags:
            print(convert(os.path.join(HERE, "runs", t)))
        sys.exit()
    jobs = [(t, y, "{}_Y{:g}".format(t, y)) for t in a.tags for y in a.Y0] if a.Y0 \
        else [(t, None, None) for t in a.tags]
    with cf.ThreadPoolExecutor(a.j) as ex:
        for tag, rc, n in ex.map(lambda j: run(*j), jobs):
            print("{}: exit {}, {} snapshots".format(tag, rc, n))
