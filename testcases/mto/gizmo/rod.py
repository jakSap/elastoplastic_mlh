#!/usr/bin/env python3
"""GIZMO control for the Taylor-rod test P1 (the reference "should look like GIZMO").

    ./rod.py w10 [w16 w24] [-j 2]     build IC from ../ics/P1_<rung>.h5, run, convert

Binary: ~/Documents/GIZMO/build_mto_elastic/GIZMO (Config.sh there): 2D, open box,
HYDRO_MESHLESS_FINITE_MASS, EOS_TILLOTSON + EOS_ELASTIC, KERNEL_FUNCTION=6,
HYDRO_EXPLICITLY_INTEGRATE_VOLUME, double-precision IO. GIZMO's von Mises return is
f = Y0^2/(2 J2) applied after every kick and drift (elastic_physics.c:106-112), which
the demonstrator reproduces with VON_MISES_PLASTICITY 1 + PLASTICITY_YIELD_GIZMO 1.
Material and run length come from ../lib/tests.py (ROD), so both codes always see the
same problem. Positions are shifted by +OFFSET into the positive quadrant for GIZMO and
shifted back on conversion; conv/NNNNNN.h5 has the demonstrator dump layout (x, v, m,
rho, u, Sxx, Sxy, Syy, time, energy), particles sorted by ID = IC order.
"""

